-- Customer order history for the Trikonic storefront.
-- The authenticated account owns every order row; customers have no access to another user's data.
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  order_number text not null unique,
  customer_name text not null,
  contact text not null,
  delivery_area text,
  notes text,
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  estimated_total numeric(12,2) not null check (estimated_total >= 0),
  currency text not null default 'GHS',
  status text not null default 'Order Received'
    check (status in ('Order Received', 'Payment Made', 'Order Placed', 'Order Shipped', 'Order Arrived in Ghana', 'Order Arrived at Warehouse', 'Order Ready for Collection', 'Order Delivered', 'Order Cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists orders_user_created_idx
  on public.orders (user_id, created_at desc);

alter table public.orders enable row level security;
revoke all on public.orders from anon, authenticated;
grant usage on schema public to authenticated;
grant select, insert on public.orders to authenticated;

drop policy if exists "Customers can read their own orders" on public.orders;
create policy "Customers can read their own orders"
  on public.orders for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Customers can create their own orders" on public.orders;
create policy "Customers can create their own orders"
  on public.orders for insert to authenticated
  with check ((select auth.uid()) = user_id);

-- Private status history: customers can read only events for orders they own.
create table if not exists public.order_status_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null
    check (status in ('Order Received', 'Payment Made', 'Order Placed', 'Order Shipped', 'Order Arrived in Ghana', 'Order Arrived at Warehouse', 'Order Ready for Collection', 'Order Delivered', 'Order Cancelled')),
  created_at timestamptz not null default now()
);
create index if not exists order_status_events_order_created_idx
  on public.order_status_events (order_id, created_at asc);
alter table public.order_status_events enable row level security;
revoke all on public.order_status_events from anon, authenticated;
grant select on public.order_status_events to authenticated;
drop policy if exists "Customers can read their own order status events" on public.order_status_events;
create policy "Customers can read their own order status events"
  on public.order_status_events for select to authenticated
  using (exists (
    select 1 from public.orders as orders
    where orders.id = order_status_events.order_id
      and orders.user_id = (select auth.uid())
  ));

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
create or replace function private.log_order_status_event()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_status_events (order_id, status)
    values (new.id, coalesce(nullif(btrim(new.status), ''), 'Order Received'));
  end if;
  return new;
end;
$$;
revoke all on function private.log_order_status_event() from public, anon, authenticated;
drop trigger if exists orders_log_status_event on public.orders;
create trigger orders_log_status_event
  after insert or update of status on public.orders
  for each row execute function private.log_order_status_event();

