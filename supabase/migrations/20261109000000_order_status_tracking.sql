-- Log every order status transition so customers can see a private tracking timeline.
create table if not exists public.order_status_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  status text not null,
  created_at timestamptz not null default now()
);

create index if not exists order_status_events_order_created_idx
  on public.order_status_events (order_id, created_at asc);

alter table public.order_status_events enable row level security;
revoke all on public.order_status_events from anon, authenticated;
grant select on public.order_status_events to authenticated;

drop policy if exists "Customers can read their own order status events" on public.order_status_events;
create policy "Customers can read their own order status events"
  on public.order_status_events for select to authenticated
  using (
    exists (
      select 1
      from public.orders as orders
      where orders.id = order_status_events.order_id
        and orders.user_id = (select auth.uid())
    )
  );

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create or replace function private.log_order_status_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.order_status_events (order_id, status)
    values (new.id, coalesce(nullif(btrim(new.status), ''), 'New'));
  elsif new.status is distinct from old.status then
    insert into public.order_status_events (order_id, status)
    values (new.id, coalesce(nullif(btrim(new.status), ''), 'New'));
  end if;
  return new;
end;
$$;

revoke all on function private.log_order_status_event() from public, anon, authenticated;

drop trigger if exists orders_log_status_event on public.orders;
create trigger orders_log_status_event
  after insert or update of status on public.orders
  for each row execute function private.log_order_status_event();

-- Backfill one baseline status event for orders already in the system.
insert into public.order_status_events (order_id, status, created_at)
select orders.id, coalesce(nullif(btrim(orders.status), ''), 'New'), orders.created_at
from public.orders as orders
where not exists (
  select 1 from public.order_status_events as events where events.order_id = orders.id
);
